//! # bus-contracts
//!
//! Rust types for the Bus event-bus HTTP API - the produce/consume
//! request/response wire contract and the durable message envelope
//! shared by every publisher and subscriber.
//!
//! # Wire stability
//!
//! Subscribers depend on this exact shape; the serde roundtrip tests pin
//! the contract, including that producers which omit optional fields
//! deserialize cleanly on the consumer side.

#![deny(missing_docs)]

use serde::{Deserialize, Serialize};
use utoipa::ToSchema;

/// A Bus message envelope.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, ToSchema)]
pub struct Message {
    /// Stream entry id (`{timestamp}-{sequence}`) or a UUID.
    pub message_id: String,
    /// The stream family the event was published to.
    pub stream_family: String,
    /// Organization ID - OPTIONAL: `env_id` is globally unique and is the
    /// sole tenant key, so this is enrichment/audit metadata only.
    #[serde(default)]
    pub org_id: String,
    /// Tenant environment the event belongs to (the tenant key).
    pub env_id: String,
    /// Platform event name - `vertical:service:resource:operation`.
    pub event_type: String,
    /// Payload schema version.
    pub schema_version: String,
    /// The domain payload.
    pub payload: serde_json::Value,
    /// Correlation id propagated from the originating request.
    pub correlation_id: String,
    /// Producing service identity.
    pub produced_by: String,
    /// RFC 3339 production timestamp.
    pub produced_at: String,
    /// Producer-supplied idempotency key for exactly-once consumers.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub idempotency_key: Option<String>,
    /// Publisher identity token - the JWT that authenticated the request
    /// which triggered this event. Enables subscriber-side delegation via
    /// RFC 8693 token exchange.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub publisher_id_token: Option<String>,
    /// Extracted `sub` claim from the publisher token - for audit/indexing.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub publisher_subject: Option<String>,
    /// The verified producer's vertical claim (design/
    /// sentin8-vertical-data-plane-contract.md §VDC.4) - recorded by Bus at
    /// produce from the M2M token. Consumers assert it against the
    /// event_type's first colon segment via `require_publisher` before
    /// acting on reaction-triggering events (defense-in-depth under the
    /// produce-side ownership gate).
    #[serde(skip_serializing_if = "Option::is_none", default)]
    pub publisher_vertical: Option<String>,
}

/// Request body for `POST /v1/produce`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default, ToSchema)]
pub struct ProduceRequest {
    /// The stream family to publish into.
    pub stream_family: String,
    /// Platform event name - `vertical:service:resource:operation`.
    pub event_type: String,
    /// The domain payload.
    pub payload: serde_json::Value,
    /// Tenant env - must match the JWT-derived tenant context (a
    /// defense-in-depth server check). Absent → the server uses the JWT
    /// claims.
    #[serde(skip_serializing_if = "Option::is_none", default)]
    pub env_id: Option<uuid::Uuid>,
    /// Correlation id; generated by the server when absent.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub correlation_id: Option<String>,
    /// Idempotency key for exactly-once consumers.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub idempotency_key: Option<String>,
    /// Publisher identity token - optional. If absent, the server derives
    /// it from the Authorization header.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub publisher_id_token: Option<String>,
    /// Publisher subject (`sub` claim). If absent, the server derives it
    /// from the verified token claims.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub publisher_subject: Option<String>,
}

/// Response from `POST /v1/produce`.
#[derive(Debug, Clone, Serialize, Deserialize, ToSchema)]
pub struct ProduceResponse {
    /// Stream entry id (format: `<timestamp>-<sequence>`) or a UUID.
    pub message_id: String,
    /// The target stream key the event was published into.
    pub stream: String,
}

/// Request body for `POST /v1/produce/batch` - N events in ONE call
/// (bus DESIGN §4.3 / README §7). Rows are independent: the batch is a
/// transport-level optimization, not a transaction.
#[derive(Debug, Clone, Serialize, Deserialize, Default, ToSchema)]
pub struct ProduceBatchRequest {
    /// The batched events (max 100 per call - matches the outbox relay
    /// drain batch).
    pub events: Vec<ProduceRequest>,
}

/// Response from `POST /v1/produce/batch`.
#[derive(Debug, Clone, Serialize, Deserialize, Default, ToSchema)]
pub struct ProduceBatchResponse {
    /// Per-row results, in request order. A failed row carries `error`
    /// and no `message_id` - the batch is best-effort per row.
    pub results: Vec<ProduceBatchItem>,
}

/// One row's produce result in a `POST /v1/produce/batch` response.
#[derive(Debug, Clone, Serialize, Deserialize, Default, ToSchema)]
pub struct ProduceBatchItem {
    /// Row index in the request.
    pub index: usize,
    /// The produced message id (on success).
    #[serde(skip_serializing_if = "Option::is_none", default)]
    pub message_id: Option<String>,
    /// The target stream (on success).
    #[serde(skip_serializing_if = "Option::is_none", default)]
    pub stream: Option<String>,
    /// The failure reason (on error).
    #[serde(skip_serializing_if = "Option::is_none", default)]
    pub error: Option<String>,
}

/// Request body for `POST /v1/consume`.
#[derive(Debug, Clone, Serialize, Deserialize, ToSchema)]
pub struct ConsumeRequest {
    /// The stream family to consume from.
    pub stream_family: String,
    /// Consumer group to read as.
    pub consumer_group: String,
    /// Maximum messages per read.
    pub max_count: u32,
    /// How long to block on XREADGROUP (milliseconds) waiting for new
    /// messages before returning empty. 0 = don't block (immediate).
    #[serde(default)]
    pub block_ms: u64,
}

/// Response from `POST /v1/consume`.
#[derive(Debug, Clone, Serialize, Deserialize, ToSchema)]
pub struct ConsumeResponse {
    /// The delivered messages (empty on timeout).
    pub messages: Vec<Message>,
}

// Serde roundtrip tests - bus envelope wire-format stability. The
// optional-field defaults (org_id, idempotency, publisher metadata) are
// pinned so producers that omit them deserialize cleanly.

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn sample_message() -> Message {
        Message {
            message_id: "1717171717171-0".into(),
            stream_family: "notifications".into(),
            org_id: "00000000-0000-0000-0000-000000000001".into(),
            env_id: "00000000-0000-0000-0000-000000000002".into(),
            event_type: "sentin8:auth:user:created".into(),
            schema_version: "1".into(),
            payload: json!({"user_id": "u-1"}),
            correlation_id: "c-1".into(),
            produced_by: "auth".into(),
            produced_at: "2026-01-01T00:00:00Z".into(),
            idempotency_key: Some("idem-1".into()),
            publisher_id_token: Some("tok".into()),
            publisher_subject: Some("sub-1".into()),
            publisher_vertical: Some("sentin8".into()),
        }
    }

    #[test]
    fn message_roundtrip() {
        let m = sample_message();
        let v = serde_json::to_value(&m).unwrap();
        assert_eq!(v["event_type"], "sentin8:auth:user:created");
        let back: Message = serde_json::from_value(v).unwrap();
        assert_eq!(back, m);
    }

    #[test]
    fn message_optional_fields_omitted_when_none() {
        let mut m = sample_message();
        m.org_id = String::new();
        m.idempotency_key = None;
        m.publisher_id_token = None;
        m.publisher_subject = None;
        let v = serde_json::to_value(&m).unwrap();
        assert!(v.get("idempotency_key").is_none());
        assert!(v.get("publisher_id_token").is_none());
        assert!(v.get("publisher_subject").is_none());
        // Roundtrip still succeeds without the optional fields.
        let back: Message = serde_json::from_value(v).unwrap();
        assert_eq!(back, m);
    }

    #[test]
    fn message_org_id_defaults_when_absent() {
        // Producers that never carried org_id must not break consumer
        // deserialization.
        let v = json!({
            "message_id": "1-0",
            "stream_family": "events",
            "env_id": "e",
            "event_type": "sentin8:x:y:z",
            "schema_version": "1",
            "payload": {},
            "correlation_id": "c",
            "produced_by": "p",
            "produced_at": "t"
        });
        let m: Message = serde_json::from_value(v).unwrap();
        assert_eq!(m.org_id, "");
    }

    #[test]
    fn event_name_segments_colon_convention() {
        // AGENTS.md: vertical:service:resource:operation - 4 colon segments.
        let m = sample_message();
        let segs: Vec<&str> = m.event_type.split(':').collect();
        assert_eq!(segs.len(), 4);
        assert!(!m.event_type.contains('.'));
    }

    #[test]
    fn produce_request_roundtrip_and_block_default() {
        let req = ProduceRequest {
            stream_family: "events".into(),
            event_type: "sentin8:ledger:posting:committed".into(),
            payload: json!({"amount": "10.00"}),
            env_id: None,
            correlation_id: Some("c".into()),
            idempotency_key: Some("i".into()),
            publisher_id_token: None,
            publisher_subject: None,
        };
        let v = serde_json::to_value(&req).unwrap();
        let back: ProduceRequest = serde_json::from_value(v).unwrap();
        assert_eq!(back, req);

        let c: ConsumeRequest = serde_json::from_value(json!({
            "stream_family": "events",
            "consumer_group": "g",
            "max_count": 10
        }))
        .unwrap();
        assert_eq!(c.block_ms, 0, "block_ms defaults to no-block");
        let resp = ProduceResponse {
            message_id: "1717171717171-0".into(),
            stream: "bus:e:events".into(),
        };
        let v = serde_json::to_value(&resp).unwrap();
        assert_eq!(v["message_id"], "1717171717171-0");
        assert_eq!(v["stream"], "bus:e:events");
        let cr: ConsumeResponse = serde_json::from_value(json!({"messages": []})).unwrap();
        assert!(cr.messages.is_empty());
    }
}
